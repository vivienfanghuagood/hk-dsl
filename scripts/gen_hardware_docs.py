#!/usr/bin/env python3
"""Write docs/supported-hardware.md and docs/ops.md from the code that decides what runs where.

    python3 scripts/gen_hardware_docs.py            # write them
    python3 scripts/gen_hardware_docs.py --check    # exit 1 if one is stale

The sources are the target table (python/hk/target/*.py: each arch's facts,
the GPUs that are that arch and the one it was measured on), the engine-route
table (python/hk/integration/switches.py) and the GPU tier's runners
(.github/workflows/gpu.yml). It also writes the page's GPU table, in four
columns, into README.md and docs/positioning.md between their hw-table markers:
those two kept tables of their own, which is how three of them came to
disagree. tests/hk/ir/test_hardware_docs.py runs `--check` over all three.

docs/ops.md, the op catalog, comes from python/hk/ops/catalog.py (every kernel family,
its GPUs, dtypes, routes and GPU tests) and the route table's defaults;
tests/hk/ir/test_ops_catalog.py holds the catalog to the code.

Needs neither hk._mlir nor a GPU: the two modules are loaded without hk's
package __init__, which imports the language.
"""

from __future__ import annotations

import argparse
import difflib
import importlib
import importlib.util
import re
import sys
import types
from pathlib import Path
from typing import Dict, List

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "docs" / "supported-hardware.md"
OPS_OUT = REPO / "docs" / "ops.md"
CATALOG = REPO / "python" / "hk" / "ops" / "catalog.py"
GPU_WORKFLOW = REPO / ".github" / "workflows" / "gpu.yml"

HEADER = ("<!-- Generated by scripts/gen_hardware_docs.py from python/hk/target/*.py, "
          "python/hk/integration/switches.py and .github/workflows/gpu.yml. Do not edit: "
          "change those and run `python3 scripts/gen_hardware_docs.py`. -->\n\n")

#: Column order: the RDNA parts, then the CDNA ones, newest last.
ARCH_ORDER = ["gfx1100", "gfx1201", "gfx942", "gfx950"]

ENGINES = {"vllm": "vLLM", "sglang": "SGLang", "sglang_diffusion": "SGLang-Diffusion",
           "ops": "`hk.ops`"}


def _load():
    """hk.target, hk.integration.switches and each arch's module: the package's own when it
    imports (its bindings are built), else loaded without running hk/__init__.py or
    hk/integration/__init__.py (both import the language, and with it hk._mlir)."""
    try:
        import hk.integration.switches as switches  # noqa: PLC0415
        import hk.target as target  # noqa: PLC0415
    except ImportError:
        return _load_without_the_package()
    return target, switches, {a: importlib.import_module(f"hk.target.{a}")
                              for a in target.TARGETS}


def _load_without_the_package():
    """As _load, under stand-in packages that are taken out of sys.modules again with
    everything loaded under them: left there, they were what a later `import hk` in the same
    process got (the IR tier's next test file found no hk.kernel)."""
    pkg = REPO / "python" / "hk"
    for name, path in (("hk", pkg), ("hk.integration", pkg / "integration")):
        m = types.ModuleType(name)
        m.__path__ = [str(path)]
        sys.modules[name] = m
    try:
        target = importlib.import_module("hk.target")
        switches = importlib.import_module("hk.integration.switches")
        return target, switches, {a: importlib.import_module(f"hk.target.{a}")
                                  for a in target.TARGETS}
    finally:
        for name in [n for n in sys.modules if n == "hk" or n.startswith("hk.")]:
            del sys.modules[name]


def ci_gpu_arches(text: str) -> List[str]:
    """The arches the GPU tier has runners for: `runs-on: [self-hosted, hk-gpu, <label>]`,
    where a label is an arch with an optional suffix (`gfx1100-x4`)."""
    return sorted({m.group(1) for m in
                   re.finditer(r"runs-on:\s*\[self-hosted,\s*hk-gpu,\s*(gfx[0-9a-f]+)", text)})


def _yes(v: bool) -> str:
    return "yes" if v else "no"


def page() -> str:
    target, switches, mods = _load()
    archs = [a for a in ARCH_ORDER if a in target.TARGETS]
    missing = sorted(set(target.TARGETS) - set(archs))
    if missing:
        raise SystemExit(f"gen_hardware_docs: add {missing} to ARCH_ORDER")
    T = target.TARGETS
    ci = ci_gpu_arches(GPU_WORKFLOW.read_text(encoding="utf-8"))
    routes = list(switches.ROUTES.values())

    out: List[str] = [HEADER, "# Supported hardware\n\n",
                      "hk-dsl builds kernels for four GPU architectures. This page is generated "
                      "from the code that decides what runs where: the target table "
                      "(`python/hk/target/`), the engine-route table "
                      "(`python/hk/integration/switches.py`) and the runners of CI's GPU tier "
                      "(`.github/workflows/gpu.yml`). `tests/hk/ir/test_hardware_docs.py` fails "
                      "when the page and the code disagree.\n\n",
                      "## GPUs\n\n",
                      "| GPU | arch | status | engine routes on by default |\n|---|---|---|---|\n"]
    for a in archs:
        t, m = T[a], mods[a]
        if t.verified:
            status = f"**runs**: measured on {m.MEASURED_ON}; " + (
                "CI's GPU tier runs on one" if a in ci else "not in CI's GPU tier")
        else:
            status = ("**compile-only**: no part was available, so its numbers are modelled "
                      "from the compiler. CI builds kernels for it; none has run on one")
        on = [r for r in routes if r.default and a in r.arches]
        if on:
            by: Dict[str, int] = {}
            for r in on:
                by[ENGINES[r.engine]] = by.get(ENGINES[r.engine], 0) + 1
            rs = f"{len(on)}: " + ", ".join(f"{e} {n}" for e, n in by.items())
        else:
            rs = "none"
        out.append(f"| {', '.join(m.PARTS)} | {a} ({t.gpu_target}) | {status} | {rs} |\n")
    aliases = sorted(target._ALIASES)
    out.append(
        "\nOther GPUs are not supported, other RDNA3 parts (gfx1101, gfx1102) included. "
        "On one, `hk.target.current_arch()` builds for gfx1100, and every engine route is off "
        "by default. `HK_ARCH` names the arch to build for, as a gfx name or as one of "
        + ", ".join(f"`{x}`" for x in aliases) + ".\n\n")

    out.append("## What the language has on each\n\n")
    out.append("| | " + " | ".join(archs) + " |\n|---" + "|---" * len(archs) + "|\n")
    rows = [
        ("lanes a wave", [str(T[a].wave) for a in archs]),
        ("`hk.mma` input types (the target's `mma` table)",
         [", ".join(T[a].mma) or "none" for a in archs]),
        ("register strips (`hk.RS`), and so `hk.templates.elementwise` / `rowwise`",
         [_yes(T[a].strips) for a in archs]),
        ("global -> LDS without passing through VGPRs (`g.load(..., wait=False)`)",
         [_yes(T[a].has_global_to_lds_dma) for a in archs]),
        ("tile fragment shapes (`hk.RT(..., frag=...)`)", [_yes(T[a].tile_shapes) for a in archs]),
    ]
    for what, cells in rows:
        out.append(f"| {what} | " + " | ".join(cells) + " |\n")
    out.append("\ngfx950 also has the block-scaled matrix ops (`hk.mma_ABt_mx`: FP8 e4m3 and FP4 "
               "operands with E8M0 scales, its `v_mfma_scale` instruction), and `hk.comm`'s "
               "hand-offs were measured on gfx950 only; neither is in the target table. The "
               "numbers behind the table (registers, LDS, granules, and where each was measured) "
               "are in [`hk.target`](api/hk.target.md).\n\n")

    out.append("## Engine routes on each\n\n")
    out.append("A route is on by default only on the GPUs it was validated on (**on** below). "
               "Elsewhere it is off: its switch at `1` turns it on anyway, without that "
               "validation, and not every route's kernels exist on every arch. A route marked "
               "opt-in is off "
               "on every GPU until you turn it on. What each route does and the evidence for "
               "its default: [integration](integration.md#on-by-default-and-turning-it-off); "
               "`python3 -m hk.integration --status` prints the decision on your machine.\n\n")
    out.append("| route | engine | switch | " + " | ".join(archs) + " |\n|---|---|---"
               + "|---" * len(archs) + "|\n")
    for r in routes:
        if r.default:
            cells = ["**on**" if a in r.arches else "off" for a in archs]
        else:
            cells = ["opt-in"] * len(archs)
        out.append(f"| `{r.name}` | {ENGINES[r.engine]} | `{r.env}` | " + " | ".join(cells)
                   + " |\n")
    return "".join(out)


def load_catalog():
    """python/hk/ops/catalog.py, read without importing hk (it is plain data)."""
    spec = importlib.util.spec_from_file_location("hk_ops_catalog", CATALOG)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _api_link(entry: str) -> str:
    """An entry's anchor on docs/api/hk.ops.md, where the page documents it; else plain code."""
    api = (REPO / "docs" / "api" / "hk.ops.md").read_text(encoding="utf-8")
    head = f"### `{entry}`"
    if head in api:
        anchor = re.sub(r"[^\w\- ]", "", entry.lower()).replace(" ", "-")
        return f"[`{entry}`](api/hk.ops.md#{anchor})"
    return f"`{entry}`"


def ops_page() -> str:
    """docs/ops.md: one row a kernel family."""
    _, switches, _ = _load()
    cat = load_catalog()
    archs = list(cat.ARCHES)
    out: List[str] = [
        HEADER.replace("python/hk/target/*.py, python/hk/integration/switches.py and "
                       ".github/workflows/gpu.yml", "python/hk/ops/catalog.py and "
                       "python/hk/integration/switches.py"),
        "# Op catalog\n\n",
        "Every kernel family `hk.ops` ships: the GPUs it runs on, what it takes, the engine "
        "routes that call it and the GPU tests that run it. Generated from "
        "`python/hk/ops/catalog.py` and the route table; `tests/hk/ir/test_ops_catalog.py` "
        "holds the catalog to the code. Signatures and docstrings: the "
        "[API reference](api/hk.ops.md). Which routes are on, per GPU: "
        "[supported hardware](supported-hardware.md#engine-routes-on-each).\n\n",
        "| family | entry points | what | " + " | ".join(archs) + " | dtypes | engine routes "
        "(on by default) | GPU tests |\n",
        "|---|---|---" + "|---" * len(archs) + "|---|---|---|\n"]
    for f in cat.FAMILIES:
        cells = ["yes" if a in f["arches"] else "--" for a in archs]
        routes = []
        for r in f["routes"]:
            rt = switches.ROUTES[r]
            on = ", ".join(a for a in archs if rt.default and a in rt.arches)
            routes.append(f"`{r}` ({'on: ' + on if on else 'opt-in' if not rt.default else 'off'})")
        what = f["what"] + (f"; {f['note']}" if f.get("note") else "")
        tests = ", ".join(f"`{t}`" for t in f["tests"])
        out.append(f"| {f['name']} | " + "<br>".join(_api_link(e) for e in f["entries"])
                   + f" | {what} | " + " | ".join(cells) + f" | {f['dtypes']} | "
                   + ("<br>".join(routes) or "--") + f" | {tests} |\n")
    out.append("\nA family that runs on a GPU has a kernel there and is run by CI's GPU tier "
               "where it has a runner for that GPU; gfx942 builds only (no part was "
               "available). A route marked off is off by default; its switch turns it on "
               "without the validation ([integration](integration.md#on-by-default-and-"
               "turning-it-off)).\n")
    return "".join(out)


#: The pages that show the GPUs at a glance, between BEGIN and END, and the page's path from each.
MARKED = {REPO / "README.md": "docs/supported-hardware.md",
          REPO / "docs" / "positioning.md": "supported-hardware.md"}
BEGIN = ("<!-- hw-table:begin -- generated by scripts/gen_hardware_docs.py from "
         "python/hk/target/*.py and switches.py; edit those and rerun it -->")
END = "<!-- hw-table:end -->"


def compact(link: str) -> str:
    """The page's GPU table in four columns, for the README and positioning.md: `link` is
    docs/supported-hardware.md's path from the page it goes into."""
    target, switches, mods = _load()
    ci = ci_gpu_arches(GPU_WORKFLOW.read_text(encoding="utf-8"))
    rows = ["| GPU | arch | level | engine routes on by default |", "|---|---|---|---|"]
    for a in [a for a in ARCH_ORDER if a in target.TARGETS]:
        t, m = target.TARGETS[a], mods[a]
        level = ("tested" if a in ci else "measured") if t.verified else "compile-only"
        n = sum(1 for r in switches.ROUTES.values() if r.default and a in r.arches)
        rows.append(f"| {', '.join(m.PARTS)} | {a} ({t.gpu_target}) | {level} | "
                    f"[{n or 'none'}]({link}#engine-routes-on-each) |")
    rows.append("")
    rows.append(f"Tested: measured on the part and run by CI's GPU tier. What the language and "
                f"each engine route do on each GPU: [supported hardware]({link}).")
    return "\n".join(rows)


def marked(path: Path, link: str) -> str:
    """`path`'s text with the compact table between its markers."""
    text = path.read_text(encoding="utf-8")
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
        raise SystemExit(f"gen_hardware_docs: {path.relative_to(REPO)} needs one {BEGIN!r} "
                         f"and one {END!r} after it")
    head, rest = text.split(BEGIN, 1)
    return head + BEGIN + "\n" + compact(link) + "\n" + END + rest.split(END, 1)[1]


def outputs() -> Dict[Path, str]:
    """Every file this script writes, and what it should hold."""
    return {OUT: page(), OPS_OUT: ops_page(), **{p: marked(p, link) for p, link in MARKED.items()}}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if a file is stale")
    args = ap.parse_args(argv)
    stale = 0
    for path, text in outputs().items():
        have = path.read_text(encoding="utf-8") if path.exists() else ""
        if have == text:
            continue
        rel = path.relative_to(REPO)
        if args.check:
            sys.stdout.writelines(difflib.unified_diff(
                have.splitlines(True), text.splitlines(True), str(rel), "generated"))
            stale += 1
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {rel}")
    if stale:
        print(f"\n{stale} file(s) stale: run `python3 scripts/gen_hardware_docs.py`")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
