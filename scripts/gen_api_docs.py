_ADDR = re.compile(r" at 0x[0-9a-f]+")


def sig(obj, name: str) -> str:
    try:
        s = str(inspect.signature(obj))
    except (TypeError, ValueError):
        return f"{name}(...)"
    s = _ADDR.sub("", s)
    s = re.sub(r"<function (\w+)>", r"\1", s)
    s = re.sub(r"<class '([\w.]+)'>", r"\1", s)
    # `from __future__ import annotations` leaves the annotations as strings.
    s = re.sub(r"(: |-> )\"'([^']*)'\"", r"\1\2", s)
    s = re.sub(r"(: |-> )'([^']*)'", r"\1\2", s)
    for alias, real in _ALIASES.items():
        s = re.sub(rf"\b{alias}\b", real, s)
    return f"{name}{s}"


#: Private aliases a signature names, by the public type they are.
_ALIASES = {"_RT": "RegTileType", "_RV": "RegVecType", "_ST": "SharedTileType",
            "_SV": "SharedVecType"}


def params_of(obj) -> Optional[List[str]]:
    try:
        ps = inspect.signature(obj).parameters.values()
    except (TypeError, ValueError):
        return None
    out = []
    for p in ps:
        if p.kind is p.VAR_POSITIONAL:
            out.append(f"*{p.name}")
        elif p.kind is p.VAR_KEYWORD:
            out.append(f"**{p.name}")
        else:
            out.append(p.name)
    return out


def doc(obj) -> str:
    d = inspect.getdoc(obj) or ""
    return d.strip()


class Since:
    """Marks against the 0.4.0 wheel's API."""

    def __init__(self, base: Dict[str, Any]):
        self.base = base

    def mark(self, module: str, name: str, obj=None, cls: Optional[str] = None) -> str:
        if not self.base:
            return ""
        names = self.base.get(module)
        if names is None:
            return f"*New after {PYPI}* (the `{module}` module is not in the {PYPI} wheel)"
        if cls is not None:
            info = names.get(cls)
            if info is None:
                return ""
            meths = info.get("methods")
            if meths is None:
                return ""
            if name not in meths:
                return f"*New after {PYPI}*"
            old = meths.get(name)
            new = params_of(obj) if obj is not None and inspect.isfunction(obj) else None
            return self._changed(old, new)
        info = names.get(name)
        if info is None:
            return f"*New after {PYPI}*"
        new = params_of(obj) if obj is not None and (inspect.isfunction(obj)
                                                     or inspect.isbuiltin(obj)) else None
        return self._changed(info.get("params"), new)

    @staticmethod
    def _changed(old, new) -> str:
        if old is None or new is None or old == new:
            return ""
        added = [p for p in new if p not in old]
        gone = [p for p in old if p not in new]
        bits = []
        if added:
            bits.append("new parameter" + ("s" if len(added) > 1 else "") + " "
                        + ", ".join(f"`{p}`" for p in added))
        if gone:
            bits.append("removed " + ", ".join(f"`{p}`" for p in gone))
        if not bits:
            bits.append("parameters reordered")
        return f"*Changed after {PYPI}*: " + "; ".join(bits)


class Page:
    def __init__(self, fname: str, title: str, intro: str = ""):
        self.fname = fname
        self.lines: List[str] = [HEADER + f"# {title}\n"]
        if intro:
            self.lines.append(intro.strip() + "\n")
        self.toc: List[str] = []
        self.empty: List[str] = []

    def h2(self, text: str):
        self.lines.append(f"## {text}\n")

    def para(self, text: str):
        self.lines.append(text.strip() + "\n")

    def entry(self, qual: str, obj, *, display: Optional[str] = None, mark: str = "",
              extra: str = "", level: int = 3, signature: bool = True):
        disp = display or qual
        full = sig(obj, disp) if signature and callable(obj) and not inspect.isclass(obj) \
            else None
        if inspect.isclass(obj) and signature and _has_init(obj):
            full = f"class {sig(obj, disp)}"
        if isinstance(obj, property):
            disp = disp + " (property)"
        self.lines.append(f"{'#' * level} `{disp}`\n")
        self.toc.append((level, disp, _anchor(disp)))
        if full:
            self.lines.append(f"```python\n{full}\n```\n")
        if mark:
            self.lines.append(mark + "\n")
        d = doc(obj)
        if d:
            self.lines.append(d + "\n")
        else:
            self.empty.append(qual)
            self.lines.append("(No docstring.)\n")
        if extra:
            self.lines.append(extra.strip() + "\n")

    def text(self) -> str:
        return "\n".join(self.lines).rstrip() + "\n"


def _has_init(cls) -> bool:
    return "__init__" in cls.__dict__ or any(
        "__init__" in c.__dict__ for c in cls.__mro__[1:] if c.__module__.startswith("hk"))


def _anchor(head: str) -> str:
    a = head.lower()
    a = re.sub(r"[^\w\- ]", "", a)
    return a.replace(" ", "-")


def members(cls) -> List[Tuple[str, Any, str]]:
    """Public methods and properties of an hk class, its hk bases' too, in
    definition order: (name, object, defining class)."""
    seen, out = set(), []
    for c in cls.__mro__:
        if not c.__module__.startswith("hk"):
            continue
        for n, v in c.__dict__.items():
            if n.startswith("_") or n in seen:
                continue
            if isinstance(v, (staticmethod, classmethod)):
                v = v.__func__
            if inspect.isfunction(v) or isinstance(v, property):
                seen.add(n)
                out.append((n, v, c.__name__))
    return out


def arch_table(name: str) -> str:
    rows = ARCH_RULES.get(name)
    if not rows:
        return ""
    t = ["**Per architecture** ([audit](../dx/api-consistency.md)):", "",
         "| | gfx1100 (RDNA3) | gfx950 (CDNA4) |", "|---|---|---|"]
    t += [f"| {w} | {a} | {b} |" for w, a, b in rows]
    return "\n".join(t)


