def outputs() -> Dict[Path, str]:
    pages = build_pages()
    files = {OUT / pg.fname: pg.text() for pg in pages}
    files[REPO / "llms-full.txt"] = llms_full(pages[1:])
    return files


def empty_docstrings() -> List[str]:
    return sorted({q for pg in build_pages() for q in pg.empty})


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if any output is stale")
    ap.add_argument("--baseline", metavar="DIR",
                    help="record the API of an unpacked hk-dsl wheel (DIR/hk/...)")
    ap.add_argument("--empty", action="store_true", help="list names with no docstring")
    args = ap.parse_args(argv)
    if args.baseline:
        base = record_baseline(Path(args.baseline))
        BASELINE.write_text(json.dumps(base, indent=0, sort_keys=True) + "\n")
        print(f"wrote {BASELINE.relative_to(REPO)}: {len(base)} modules")
        return 0
    if args.empty:
        print("\n".join(empty_docstrings()))
        return 0
    files = outputs()
    stale = []
    for path, text in files.items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old == text:
            continue
        stale.append(path)
        if args.check:
            diff = difflib.unified_diff((old or "").splitlines(), text.splitlines(),
                                        str(path.relative_to(REPO)), "generated", lineterm="",
                                        n=1)
            print("\n".join(list(diff)[:40]))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    known = {OUT / pg for pg in os.listdir(OUT)} if OUT.is_dir() else set()
    extra = sorted(p for p in known if p.suffix == ".md" and p not in files)
    if args.check:
        if stale or extra:
            print("\nstale: " + ", ".join(str(p.relative_to(REPO)) for p in stale + extra)
                  + "\nregenerate with: python3 scripts/gen_api_docs.py")
            return 1
        print("docs/api and llms-full.txt are current")
        return 0
    for p in extra:
        p.unlink()
    print(f"wrote {len(stale)} of {len(files)} files"
          + (f", removed {len(extra)}" if extra else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
