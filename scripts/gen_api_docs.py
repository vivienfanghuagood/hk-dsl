def page_hk(since: Since) -> Page:
    import hk

    p = Page("hk.md", "`hk`: kernels, types, values",
             "The language: what `import hk` gives a kernel author. A kernel body is "
             "traced once per set of constexprs; [the language](../language.md) says "
             "how it is written, this page what each name is. The namespaces have "
             "pages of their own: [hk.math](hk.math.md), [hk.arch](hk.arch.md), "
             "[hk.lds](hk.lds.md), [hk.group](hk.group.md), "
             "[hk.collective](hk.collective.md); the shipped kernels are "
             "[hk.ops](hk.ops.md), the templates [hk.templates](hk.templates.md), "
             "the checker [hk.check](hk.check.md), the per-arch facts "
             "[hk.target](hk.target.md).")
    groups = [
        ("Kernels", ["kernel", "func", "Kernel", "TracedKernel", "Tensor", "Constexpr"]),
        ("Types", ["RT", "RS", "ST", "SV", "col_vec", "row_vec", "DType"]),
        ("Control flow", ["range", "range_constexpr", "if_", "scope"]),
        ("Functions", ["cdiv", "min", "max", "zeros", "full", "neg_infty", "rand",
                       "transpose", "transpose_sep", "broadcast_row", "broadcast_col",
                       "as_vec", "mma", "load_w4", "coord", "tile_coord", "elem_coord"]),
    ]
    documented = set()
    for title, names in groups:
        p.h2(title)
        for n in names:
            obj = getattr(hk, n)
            documented.add(n)
            p.entry(f"hk.{n}", obj, display=f"hk.{n}",
                    mark=_mark(since, "hk", n, obj, f"hk.{n}"))
            if inspect.isclass(obj) and n in ("Kernel", "TracedKernel"):
                for mn, mv, _ in members(obj):
                    p.entry(f"hk.{n}.{mn}", mv, display=f"{n}.{mn}", level=4,
                            mark=since.mark("hk.dsl.kernel", mn, mv, cls=n),
                            signature=not isinstance(mv, property))
    p.h2("Dtypes")
    p.para("| name | bits | C++ | kind |\n|---|---|---|---|\n" + "\n".join(
        f"| `hk.{d.name}` | {d.bits} | `{d.cpp}` | {d.kind} |" for d in hk.DTYPES.values())
        + "\n\nfp8 is a WMMA operand only where the target has an fp8 matrix "
          "instruction (gfx1201); i8 is a storage type (quantize into it, "
          "dequantize out of it). `hk.DTYPES` maps the names to these.")
    documented |= {d for d in hk.DTYPES} | {"DTYPES"}
    p.h2("Device values")
    p.para("What a kernel body computes with. They are made by loads, `hk.zeros` "
           "and friends, never constructed directly; their methods are the "
           "language. A method ending in `_` writes the value in place; `into=` "
           "names the value an operation writes.")
    p.para(operator_table())
    for n in ["Tile", "Vec", "Global", "View", "SharedTile", "SharedVec", "Granules",
              "Int", "Bool", "Coord"]:
        obj = getattr(hk, n)
        documented.add(n)
        p.entry(f"hk.{n}", obj, display=f"hk.{n}", signature=False,
                mark=_mark(since, "hk", n, obj, f"hk.{n}"))
        for mn, mv, owner in members(obj):
            p.entry(f"hk.{n}.{mn}", mv, display=f"{n}.{mn}", level=4,
                    mark=since.mark(mv.__module__ if hasattr(mv, "__module__") else
                                    "hk.dsl.values", mn, mv, cls=owner)
                    if not isinstance(mv, property) else "",
                    signature=not isinstance(mv, property))
    p.h2("Namespaces")
    p.para("\n".join(f"- [`hk.{n}`](hk.{n}.md)" for n in
                     ("arch", "lds", "math", "group", "collective"))
           + "\n- `hk.Group`: what `hk.group(n)` returns, on [hk.group](hk.group.md)")
    documented |= {"arch", "lds", "math", "group", "collective", "Group"}
    p.h2("Runtime, errors and the rest")
    for n in ["VerifyError", "CompileError", "ResourceError", "Build", "get_target",
              "TARGETS", "detect_arch", "torch_op", "attention"]:
        obj = getattr(hk, n)
        documented.add(n)
        if n == "TARGETS":
            p.lines.append("### `hk.TARGETS`\n")
            p.toc.append((3, "hk.TARGETS", "hktargets"))
            p.para("The known targets by gfx name, `hk.target.Target` records: see "
                   "[hk.target](hk.target.md).")
            continue
        p.entry(f"hk.{n}", obj, display=f"hk.{n}",
                mark=_mark(since, "hk", n, obj, f"hk.{n}"),
                extra=arch_table("attention") if n == "attention" else "")
        if n == "Build":
            for mn, mv, _ in members(obj):
                p.entry(f"hk.Build.{mn}", mv, display=f"Build.{mn}", level=4)
    p.h2("Tools")
    p.para("- `hk.check(fn, reference, inputs)`, `python -m hk.check`: correctness, "
           "resources and timing in one call: [hk.check](hk.check.md), "
           "[docs/check.md](../check.md).")
    documented |= {"autotune", "codegen", "compiler", "dsl", "ops", "runtime", "target",
                   "__version__"}
    missing = sorted(set(hk.__all__) - documented)
    if missing:
        p.h2("Also exported")
        p.para(", ".join(f"`hk.{m}`" for m in missing))
    return p


#: Python operators and the methods that implement them, in the order shown.
OPERATORS = [
    ("a + b", "__add__"), ("n + a", "__radd__"), ("a - b", "__sub__"),
    ("n - a", "__rsub__"), ("a * b", "__mul__"), ("n * a", "__rmul__"),
    ("a / b", "__truediv__"), ("n / a", "__rtruediv__"), ("a // b", "__floordiv__"),
    ("a % b", "__mod__"), ("-a", "__neg__"), ("abs(a)", "__abs__"),
    ("a += b (also -= *= /=)", "__iadd__"), ("a @ b", "__matmul__"),
    ("a < b (<= > >= == !=)", "__lt__"), ("a & b, a | b, a ^ b", "__and__"),
    ("~a", "__invert__"), ("v[:, None], v[None, :]", "__getitem__"),
]


def operator_table() -> str:
    """Which operator each device value takes, read off the classes: a
    method that raises (`//` on a tile) is "refused"."""
    import hk

    classes = [hk.Tile, hk.Vec, hk.Int, hk.Bool]
    rows = ["**Operators** (`n` a Python number, `a`, `b` values of the column's "
            "kind; a vector broadcasts against a tile along the axis it was "
            "reduced from):", "",
            "| operator | " + " | ".join(f"`{c.__name__}`" for c in classes) + " |",
            "|---" * (len(classes) + 1) + "|"]
    for text, dunder in OPERATORS:
        cells = []
        for c in classes:
            fn = getattr(c, dunder, None)
            own = fn is not None and any(dunder in k.__dict__ for k in c.__mro__
                                         if k.__module__.startswith("hk"))
            if not own:
                rebinds = dunder == "__iadd__" and any(
                    "__add__" in k.__dict__ for k in c.__mro__ if k.__module__.startswith("hk"))
                cells.append("yes (rebinds)" if rebinds else "")
                continue
            try:
                src = inspect.getsource(fn)
            except (OSError, TypeError):
                src = ""
            refused = "_index_only" in src or ("raise" in src and "return" not in src)
            cells.append("refused" if refused else "yes")
        cell = text.replace("|", "\\|")       # a pipe inside a table cell
        rows.append(f"| `{cell}` | " + " | ".join(cells) + " |")
    rows += ["", "`acc += a @ b.T` is one matrix-core instruction into `acc` (the "
             "variant follows from the transposes); `t.sum(axis=1)` and friends "
             "are lazy reductions that `+=`, `max_` or `.value()` land."]
    return "\n".join(rows)


def _mark(since: Since, module: str, name: str, obj, public: str) -> str:
    bits = [since.mark(module, name, obj)]
    if BEHAVIOUR.get(public):
        bits.append(f"*Changed after {PYPI}*: {BEHAVIOUR[public]}")
    return "\n\n".join(b for b in bits if b)


def page_module(since: Since, modname: str, title: str, intro: str = "",
                names: Optional[Iterable[str]] = None, extra_names: Iterable[str] = (),
                notes: Optional[Dict[str, str]] = None) -> Page:
    mod = importlib.import_module(modname)
    public = modname.replace("hk.dsl.", "hk.")
    p = Page(f"{public}.md", f"`{public}`", intro or doc(mod))
    names = list(names if names is not None else getattr(mod, "__all__", []))
    names += [n for n in extra_names if n not in names]
    for n in names:
        obj = getattr(mod, n)
        mark = _mark(since, modname, n, obj, f"{public}.{n}")
        if not callable(obj) or isinstance(obj, (dict, tuple, list)):
            p.lines.append(f"### `{public}.{n}`\n")
            p.toc.append((3, f"{public}.{n}", _anchor(f"{public}.{n}")))
            if mark:
                p.lines.append(mark + "\n")
            val = obj if isinstance(obj, (dict, tuple, list, str, int, float)) else None
            p.para(_value_doc(mod, n) or (f"`{val!r}`" if val is not None else ""))
            if notes and n in notes:
                p.para(notes[n])
            continue
        p.entry(f"{public}.{n}", obj, display=f"{public}.{n}", mark=mark,
                extra=(notes or {}).get(n, ""))
        if inspect.isclass(obj):
            for mn, mv, owner in members(obj):
                p.entry(f"{public}.{n}.{mn}", mv, display=f"{n}.{mn}", level=4,
                        mark=since.mark(modname, mn, mv, cls=owner),
                        signature=not isinstance(mv, property))
    return p


def _value_doc(mod, name: str) -> str:
    """The `#:` comment above a module-level assignment."""
    try:
        src = inspect.getsource(mod).splitlines()
    except (OSError, TypeError):
        return ""
    for i, line in enumerate(src):
        if re.match(rf"^{re.escape(name)}\s*[:=]", line):
            j, out = i - 1, []
            while j >= 0 and src[j].lstrip().startswith("#:"):
                out.insert(0, src[j].lstrip()[2:].strip())
                j -= 1
            return " ".join(out)
    return ""


