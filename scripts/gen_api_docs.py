def build_pages() -> List[Page]:
    since = Since(load_baseline())
    pages = [page_hk(since), page_math(since)]
    pages.append(page_module(since, "hk.dsl.arch", "hk.arch",
                             extra_names=["target"]))
    pages.append(page_module(since, "hk.dsl.lds", "hk.lds"))
    pages.append(page_module(since, "hk.dsl.group", "hk.group"))
    pages.append(page_module(since, "hk.dsl.collective", "hk.collective"))
    pages.append(page_ops(since))
    pages.append(page_templates(since))
    pages.append(page_schedules(since))
    pages.append(page_check(since))
    pages.append(page_target(since))
    for pg in pages:
        _add_toc(pg)
    return [page_index(pages)] + pages


def _add_toc(pg: Page) -> None:
    items = [f"- [`{d}`](#{a})" for lvl, d, a in pg.toc if lvl == 3]
    if len(items) > 3:
        pg.lines.insert(2, "\n".join(items) + "\n")


