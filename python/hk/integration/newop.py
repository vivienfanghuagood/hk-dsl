def render(name: str, path: str) -> dict:
    """{file name: text} for an op called `name` at `path` (the module's path
    as the user will type it, for the docstring)."""
    return {f"{name}.py": MODULE.replace("__NAME__", name).replace("__PATH__", path),
            f"test_{name}.py": TEST.replace("__NAME__", name)}


def valid(name: str) -> str:
    """Why `name` cannot be an op's name, or ""."""
    if not re.fullmatch(r"[a-z_][a-z0-9_]*", name) or keyword.iskeyword(name):
        return "an op's name is a lowercase Python identifier (it is a torch op name)"
    return ""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m hk.integration new-op",
                                 description=__doc__.splitlines()[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter,
                                 epilog="\n".join(__doc__.splitlines()[1:]))
    ap.add_argument("name")
    ap.add_argument("--dir", default=".", help="where the two files go (default: here)")
    ap.add_argument("--force", action="store_true", help="overwrite files that exist")
    args = ap.parse_args(argv)
    why = valid(args.name)
    if why:
        ap.error(f"{args.name!r}: {why}")
    d = Path(args.dir)
    files = render(args.name, str(d / f"{args.name}.py"))
    there = [f for f in files if (d / f).exists()]
    if there and not args.force:
        print(f"not overwriting {', '.join(str(d / f) for f in there)} (--force does)")
        return 1
    d.mkdir(parents=True, exist_ok=True)
    for f, text in files.items():
        (d / f).write_text(text)
        print(f"wrote {d / f}")
    m = d / f"{args.name}.py"
    print(f"\nnext:\n  python3 -m pytest {d / f'test_{args.name}.py'}\n  python3 {m}\n"
          f"  python3 tools/hk-bench/scoreboard.py --cases {m}\n"
          f"  then set PATCH_TARGET and: HK_VLLM_USER={m} python -m hk.integration ab "
          f"--arms user\n  (docs/agents.md says what each number is worth)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
