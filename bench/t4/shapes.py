"""T4's shape sets, from models' MoE layers.

    python3 -m bench.t4.shapes                      # rewrite shapes_public.json
    python3 -m bench.t4.shapes --check              # the committed file is what this draws
    python3 -m bench.t4.shapes --models M.json --out S.json    # another set (the sealed one)

A model entry: {"model", "E" (routed experts), "top_k", "H" (hidden), "I"
(an expert's intermediate size), "tp" (tensor-parallel ranks: each holds
I / tp of every expert), "cases": [[proj, tokens, skew], ...]}. A case is one
of the layer's two expert GEMMs at a batch of `tokens` tokens:

    gate_up   N = 2 I / tp, K = H        (vLLM's w13, gate and up fused)
    down      N = H,        K = I / tp   (w2)

with rows = tokens x top_k and the routing skew (reference.group_sizes).
Every shape's seed is drawn from the set's master seed; a shape whose call
is too big for a GPU (FLOP_CAP) is left out of that GPU's list.
"""

from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path
from typing import Dict, List

from . import reference as R

HERE = Path(__file__).resolve().parent

#: Largest call (FLOPs) a GPU's list holds: ~10 ms on a W7900D, ~2 ms on an MI355X.
FLOP_CAP = {"gfx950": 4.0e12, "gfx1100": 0.8e12}

#: The public (development) set: models from vLLM's supported MoE list, at
#: batches a server prefills and decodes. Real configs (each model's
#: config.json); TP shards I as vLLM does.
PUBLIC_MODELS: List[Dict] = [
    {"model": "OLMoE-1B-7B", "E": 64, "top_k": 8, "H": 2048, "I": 1024, "tp": 1,
     "cases": [["gate_up", 4096, 0.6], ["down", 512, 0.6]]},
    {"model": "Mixtral-8x7B", "E": 8, "top_k": 2, "H": 4096, "I": 14336, "tp": 4,
     "cases": [["gate_up", 2048, 0.3], ["down", 4096, 0.3]]},
    {"model": "Qwen1.5-MoE-A2.7B", "E": 60, "top_k": 4, "H": 2048, "I": 1408, "tp": 1,
     "cases": [["gate_up", 512, 0.8], ["down", 4096, 0.8]]},
    {"model": "Granite-3.1-3B-A800M", "E": 40, "top_k": 8, "H": 1536, "I": 512, "tp": 1,
     "cases": [["gate_up", 1024, 0.5], ["down", 8192, 0.5]]},
    {"model": "DeepSeek-V2", "E": 160, "top_k": 6, "H": 5120, "I": 1536, "tp": 8,
     "cases": [["gate_up", 4096, 1.0], ["down", 1024, 1.0]]},
    {"model": "Qwen2-57B-A14B", "E": 64, "top_k": 8, "H": 3584, "I": 2560, "tp": 8,
     "cases": [["gate_up", 256, 0.7], ["down", 2048, 0.7]]},
]
PUBLIC_SEED = 20261023


def build(models: List[Dict], master_seed: int) -> Dict[str, List[Dict]]:
    rng = random.Random(master_seed)
    shapes = []
    for m in models:
        i_tp = m["I"] // m["tp"]
        if m["I"] % m["tp"]:
            raise ValueError(f"{m['model']}: I={m['I']} does not split {m['tp']} ways")
        for proj, tokens, skew in m["cases"]:
            n, k = (2 * i_tp, m["H"]) if proj == "gate_up" else (m["H"], i_tp)
            tp = f"-tp{m['tp']}" if m["tp"] > 1 else ""
            s = dict(name=f"{m['model'].lower()}{tp}-{proj}-t{tokens}", model=m["model"],
                     proj=proj, E=m["E"], N=n, K=k, tokens=tokens, top_k=m["top_k"],
                     skew=skew, seed=rng.randrange(1, 2**31), tp=m["tp"])
            R.validate(s)
            shapes.append(s)
    return {arch: [s for s in shapes if R.flops(s) <= cap] for arch, cap in FLOP_CAP.items()}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--models", default="", help="a models JSON (default: the public set)")
    ap.add_argument("--seed", type=int, default=None, help="master seed (default: the set's)")
    ap.add_argument("--out", default="", help="output (default shapes_public.json)")
    ap.add_argument("--check", action="store_true", help="fail if the output file differs")
    args = ap.parse_args(argv)
    if args.models:
        spec = json.loads(Path(args.models).read_text())
        models, seed = spec["models"], spec["seed"] if args.seed is None else args.seed
    else:
        models, seed = PUBLIC_MODELS, PUBLIC_SEED if args.seed is None else args.seed
    out = Path(args.out) if args.out else R.PUBLIC
    doc = dict(note="bench/t4 shapes: generated by python3 -m bench.t4.shapes; do not edit",
               **build(models, seed))
    text = json.dumps(doc, indent=1) + "\n"
    if args.check:
        same = out.is_file() and out.read_text() == text
        print(f"{out}: {'matches' if same else 'DIFFERS from'} what the seed draws")
        return 0 if same else 1
    out.write_text(text)
    for arch in FLOP_CAP:
        print(f"{arch}: {len(doc[arch])} shapes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
